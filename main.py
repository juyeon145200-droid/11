import streamlit as st
from google import genai
from google.genai import types


# ==========================================
# 페이지 설정
# ==========================================
st.set_page_config(
    page_title="☁️ 하늘 사진으로 구름 종류 알아맞히기",
    page_icon="☁️",
    layout="centered"
)


# ==========================================
# 제목
# ==========================================
st.title("☁️ 하늘 사진으로 구름 종류 알아맞히기")

st.write(
    "하늘 사진을 업로드하면 AI가 사진 속 구름을 분석하여 "
    "구름 종류, 형성 고도, 예상되는 날씨와 기상 특성을 알려줍니다."
)

st.info(
    "📸 JPG, JPEG, PNG 형식의 하늘 사진을 업로드해 주세요."
)


# ==========================================
# Gemini API 키 가져오기
# ==========================================
try:
    api_key = st.secrets["GEMINI_API_KEY"]
except Exception:
    st.error("❌ Gemini API 키를 찾을 수 없습니다.")

    st.markdown(
        """
        Streamlit Cloud의 **Settings → Secrets**에 다음과 같이 입력했는지 확인해 주세요.

        ```toml
        GEMINI_API_KEY = "여기에_Gemini_API_키"
        ```
        """
    )

    st.stop()


# Gemini 클라이언트
client = genai.Client(api_key=api_key)


# ==========================================
# 이미지 업로드
# ==========================================
uploaded_file = st.file_uploader(
    "☁️ 하늘 사진을 선택하세요",
    type=["jpg", "jpeg", "png"]
)


# ==========================================
# 업로드된 사진 표시
# ==========================================
if uploaded_file is not None:

    image_bytes = uploaded_file.getvalue()

    st.divider()

    st.subheader("📸 업로드한 사진")

    st.image(
        image_bytes,
        caption=uploaded_file.name,
        use_container_width=True
    )

    st.divider()

    # ======================================
    # 분석 버튼
    # ======================================
    if st.button(
        "🔍 AI에게 구름 종류 알아맞히기!",
        use_container_width=True
    ):

        with st.spinner("☁️ 하늘 사진을 분석하고 있어요..."):

            try:

                # ----------------------------------
                # AI에게 전달할 분석 요청
                # ----------------------------------
                prompt = """
당신은 기상학과 구름 분류를 공부하는 학생을
도와주는 교육용 AI입니다.

업로드된 하늘 사진을 자세히 관찰하고
사진에서 가장 가능성이 높은 구름 종류를 판단하세요.

다음 5대 운형 중 하나를 선택해야 합니다.

① 권운
② 권적운
③ 권층운
④ 고적운
⑤ 층운·적운·난층운·적란운 등 하층운

사진만으로 정확한 구름 종류를 확정하기 어려운 경우에는
가장 가능성이 높은 종류를 선택하고
'사진만으로 판단한 추정입니다'라고 밝혀 주세요.

다음 형식으로 답변하세요.

☁️ 구름 종류
- 가장 가능성이 높은 구름 종류
- 사진에서 그렇게 판단한 이유

⛰️ 형성 고도
- 일반적인 형성 고도 범위
- 고도에 대한 간단한 설명

🌦️ 예상되는 날씨 / 기상 특성
- 해당 구름이 나타날 때 나타날 수 있는 일반적인 날씨
- 강수나 날씨 변화와 관련된 특징

🔎 사진에서 관찰한 특징
- 구름의 모양
- 배열
- 색과 밝기
- 투명도
- 구름의 크기

⚠️ 주의
사진 한 장만으로 실제 현재 날씨나 앞으로의 날씨를
확정할 수 없다는 점을 마지막에 한 문장으로 알려주세요.

답변은 고등학생이 이해하기 쉽도록
간결하고 깔끔하게 작성하세요.
"""

                # ----------------------------------
                # Gemini에 이미지 + 질문 전달
                # ----------------------------------
                response = client.models.generate_content(
                    model="gemini-2.5-flash-lite",
                    contents=[
                        types.Part.from_bytes(
                            data=image_bytes,
                            mime_type=uploaded_file.type
                        ),
                        prompt
                    ]
                )

                # ----------------------------------
                # 결과 출력
                # ----------------------------------
                st.success("✅ 구름 분석이 완료되었습니다!")

                st.subheader("🔎 AI 구름 분석 결과")

                st.markdown(response.text)

            except Exception as e:

                st.error("❌ 사진을 분석하는 중 오류가 발생했습니다.")

                st.warning(
                    f"""
오류 내용:

`{str(e)}`

다음 사항을 확인해 주세요.

• Gemini API 키가 올바른지 확인
• Streamlit Secrets의 이름이 `GEMINI_API_KEY`인지 확인
• Gemini API 사용량 제한을 확인
• JPG, JPEG, PNG 이미지인지 확인
"""
                )

else:

    # ======================================
    # 사진을 아직 업로드하지 않았을 때
    # ======================================
    st.markdown(
        """
        ### 🌤️ 사용 방법

        **① 하늘 사진을 업로드하세요.**

        **② 사진을 확인한 후 분석 버튼을 누르세요.**

        **③ AI가 다음 내용을 분석합니다.**

        ☁️ **구름 종류**

        ⛰️ **형성 고도**

        🌦️ **예상되는 날씨 / 기상 특성**

        🔎 **사진에서 관찰한 특징**
        """
    )


# ==========================================
# 하단 안내
# ==========================================
st.divider()

st.caption(
    "☁️ AI를 활용한 교육용 구름 분류 프로젝트입니다. "
    "사진 한 장만으로 실제 날씨를 확정할 수는 없습니다."
)
